SELECT
    a.SOURCE_DATA:name:official::VARCHAR AS COUNTRY_OFFICIAL_NAME,
    a.SOURCE_DATA:name:common::VARCHAR AS COUNTRY_COMMON_NAME,
    TO_VARCHAR(a.SOURCE_DATA:latlng) AS COUNTRY_LATLNG,
    con.VALUE::VARCHAR AS COUNTRY_CONTINENT_NAME,
    a.SOURCE_DATA:region::VARCHAR AS COUNTRY_REGION_NAME,
    a.SOURCE_DATA:subregion::VARCHAR AS COUNTRY_SUBREGION_NAME,
    a.SOURCE_DATA:capital[0]::VARCHAR AS COUNTRY_CAPITAL_NAME,
    TO_VARCHAR(a.SOURCE_DATA:capitalInfo:latlng) AS COUNTRY_CAPITAL_LATLNG,
    a.SOURCE_DATA:area::NUMBER(18, 2) AS COUNTRY_TOTAL_AREA,
    a.SOURCE_DATA:population::NUMBER(38, 0) AS COUNTRY_POPULATION,
    cur.KEY::VARCHAR AS COUNTRY_CURRENCY,
    cur.VALUE:name::VARCHAR AS COUNTRY_CURRENCY_NAME,
    cur.VALUE:symbol::VARCHAR AS COUNTRY_CURRENCY_SYMBOL,
    a.SOURCE_DATA:flags:png::VARCHAR AS COUNTRY_FLAG,
    a.SOURCE_DATA:maps:googleMaps::VARCHAR AS COUNTRY_MAP,
    TO_VARCHAR(a.SOURCE_DATA:languages) AS COUNTRY_LANGUAGE,
    a.SOURCE_DATA:startOfWeek::VARCHAR AS COUNTRY_START_OF_WEEK,
    a.SOURCE_DATA:unMember::BOOLEAN AS COUNTRY_UN_MEMBER_STATUS,
    a.SOURCE_DATA:car:side::VARCHAR AS COUNTRY_DRIVING_LANE,
    CURRENT_TIMESTAMP(6) AS INSERT_DTS
FROM {{ ref('country_details_raw') }} AS a,
     LATERAL FLATTEN(
         INPUT => a.SOURCE_DATA:continents,
         OUTER => TRUE
     ) AS con,
     LATERAL FLATTEN(
         INPUT => a.SOURCE_DATA:currencies,
         OUTER => TRUE
     ) AS cur